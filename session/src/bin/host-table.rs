//! Print the host method table as TypeScript. Single source: `session::io`.
//!
//! Usage: `cargo run -p session --bin host-table > frameworks/modules/src/host-table.gen.ts`
//! The `host_table_matches_generated_file` test fails when the file drifts.

fn main() {
    println!("// Generated by `cargo run -p session --bin host-table`. Do not edit.");
    println!("export type HostPlace = \"session\" | \"platform\";");
    println!("export type HostWait = \"sync\" | \"promise\";");
    println!();
    println!("export interface HostMethodRow {{");
    println!("  module: string;");
    println!("  method: string;");
    println!("  place: HostPlace;");
    println!("  wait: HostWait;");
    println!("}}");
    println!();
    println!("export const HOST_METHODS: readonly HostMethodRow[] = [");
    let mut modules: Vec<&'static str> = Vec::new();
    for method in session::all_host_methods() {
        if !modules.contains(&method.module) {
            modules.push(method.module);
        }
        let place = match method.place {
            session::HostPlace::Session => "session",
            session::HostPlace::Platform => "platform",
        };
        let wait = match method.wait {
            session::HostWait::Sync => "sync",
            session::HostWait::Promise => "promise",
        };
        println!(
            "  {{ module: \"{}\", method: \"{}\", place: \"{}\", wait: \"{}\" }},",
            method.module, method.name, place, wait
        );
    }
    println!("];");
    println!();
    println!("export const HOST_MODULES: readonly string[] = [");
    for module in modules {
        println!("  \"{module}\",");
    }
    println!("];");
    println!();
    println!("export function hasModuleMethod(name: string, method: string): boolean {{");
    println!("  return HOST_METHODS.some((row) => row.module === name && row.method === method);");
    println!("}}");
}

//! Print the host method table as TypeScript. Kind snapshot of the public contract.
//!
//! Usage: `cargo run -p session --bin host-table > frameworks/modules/src/host-table.gen.ts`
//! The `host_table_matches_generated_file` test fails when the file drifts.

const HOST_METHODS: &[(&str, &str, &str)] = &[
    ("AppState", "getCurrentState", "sync"),
    ("Linking", "getInitialURL", "sync"),
    ("Linking", "openURL", "promise"),
    ("Clipboard", "getString", "sync"),
    ("Clipboard", "setString", "sync"),
    ("FileSystem", "documentDirectory", "sync"),
    ("FileSystem", "read", "promise"),
    ("FileSystem", "write", "promise"),
    ("FileSystem", "delete", "promise"),
    ("FileSystem", "pick", "promise"),
    ("AsyncStorage", "multiGet", "promise"),
    ("AsyncStorage", "multiSet", "promise"),
    ("AsyncStorage", "multiRemove", "promise"),
    ("AsyncStorage", "clear", "promise"),
    ("Permissions", "checkPermissionStatus", "promise"),
    ("Permissions", "requestPermissions", "promise"),
    (
        "Permissions",
        "shouldShowRequestPermissionRationale",
        "promise",
    ),
    ("Permissions", "checkServiceStatus", "promise"),
    ("Permissions", "openAppSettings", "promise"),
];

fn main() {
    println!("// Generated by `cargo run -p session --bin host-table`. Do not edit.");
    println!("export type HostWait = \"sync\" | \"promise\";");
    println!();
    println!("export interface HostMethodRow {{");
    println!("  module: string;");
    println!("  method: string;");
    println!("  wait: HostWait;");
    println!("}}");
    println!();
    println!("export const HOST_METHODS: readonly HostMethodRow[] = [");
    let mut modules: Vec<&str> = Vec::new();
    for (module, method, wait) in HOST_METHODS {
        if !modules.contains(module) {
            modules.push(module);
        }
        println!("  {{ module: \"{module}\", method: \"{method}\", wait: \"{wait}\" }},");
    }
    println!("];");
    println!();
    println!("export const HOST_MODULES: readonly string[] = [");
    for module in modules {
        println!("  \"{module}\",");
    }
    println!("];");
    println!();
    println!("export function hasModuleMethod(name: string, method: string): boolean {{");
    println!("  return HOST_METHODS.some((row) => row.module === name && row.method === method);");
    println!("}}");
}

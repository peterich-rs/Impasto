//! Type stubs for `@uifw/<pkg>/host`. Names and kind only.

use std::path::{Path, PathBuf};
use std::sync::Arc;

use session::{HostModule, Invoke};

use crate::modules::{
    app_state, async_storage, clipboard, file_system, linking,
    memory::{DeniedPermissions, MemoryClipboard, MemoryStorage, NullLinking},
    permissions,
};

pub fn first_party_modules() -> Vec<HostModule> {
    let clipboard_host = MemoryClipboard::new("");
    let storage = MemoryStorage::new("/tmp/uifw-docs");
    vec![
        app_state(session::shared("active".to_owned())),
        linking(Arc::new(NullLinking), session::shared(None)),
        clipboard(clipboard_host),
        file_system(Arc::clone(&storage) as _),
        async_storage(storage),
        permissions(Arc::new(DeniedPermissions)),
    ]
}

pub fn package_folder(specifier: &str) -> Option<&str> {
    specifier.strip_prefix("@uifw/")?.strip_suffix("/host")
}

pub fn host_stub_source(module: &HostModule) -> String {
    let mut out =
        String::from("// Generated by `cargo run -p hostshell --bin host-stubs`. Do not edit.\n");
    for method in &module.methods {
        match &method.invoke {
            Invoke::Sync(_) => {
                out.push_str("export declare function ");
                out.push_str(method.name);
                out.push_str("(): unknown;\n");
            }
            Invoke::Promise(_) => {
                out.push_str("export declare function ");
                out.push_str(method.name);
                out.push_str("(): Promise<unknown>;\n");
            }
        }
    }
    out.push_str(
        "export declare function addEventListener(type: string, listener: (e: unknown) => void): void;\n",
    );
    out.push_str(
        "export declare function removeEventListener(type: string, listener: (e: unknown) => void): void;\n",
    );
    out
}

pub fn host_stub_path(root: &Path, specifier: &str) -> Option<PathBuf> {
    let folder = package_folder(specifier)?;
    Some(
        root.join("frameworks")
            .join(folder)
            .join("src")
            .join("host.gen.ts"),
    )
}

pub fn write_host_stubs(root: &Path) -> Result<(), String> {
    for module in first_party_modules() {
        let Some(path) = host_stub_path(root, module.specifier) else {
            continue;
        };
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|error| format!("{path:?}: {error}"))?;
        }
        std::fs::write(&path, host_stub_source(&module))
            .map_err(|error| format!("{}: {error}", path.display()))?;
    }
    Ok(())
}

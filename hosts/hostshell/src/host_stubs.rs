//! Type stubs for `@uifw/<pkg>/host`. Names and kind only.

use std::path::{Path, PathBuf};
use std::sync::Arc;

use session::{HostModule, Invoke};

use crate::modules::{
    app_state, async_storage, clipboard, file_system, linking,
    memory::{DeniedPermissions, MemoryClipboard, MemoryStorage, NullLinking},
    permissions,
};

pub fn first_party_modules() -> Vec<HostModule> {
    let clipboard_host = MemoryClipboard::new("");
    let storage = MemoryStorage::new("/tmp/uifw-docs");
    vec![
        app_state(session::shared("active".to_owned())),
        linking(Arc::new(NullLinking), session::shared(None)),
        clipboard(clipboard_host),
        file_system(Arc::clone(&storage) as _),
        async_storage(storage),
        permissions(Arc::new(DeniedPermissions)),
    ]
}

pub fn package_folder(specifier: &str) -> Option<&str> {
    specifier.strip_prefix("@uifw/")?.strip_suffix("/host")
}

pub fn host_stub_source(module: &HostModule) -> String {
    let mut out =
        String::from("// Generated by `cargo run -p hostshell --bin host-stubs`. Do not edit.\n");
    for method in &module.methods {
        let signature = match &method.invoke {
            Invoke::Sync(_) => "(): unknown;",
            Invoke::Promise(_) => "(): Promise<unknown>;",
        };
        push_declared_fn(&mut out, method.name, signature);
    }
    push_declared_fn(
        &mut out,
        "addEventListener",
        "(type: string, listener: (e: unknown) => void): void;",
    );
    push_declared_fn(
        &mut out,
        "removeEventListener",
        "(type: string, listener: (e: unknown) => void): void;",
    );
    out
}

fn is_binding_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !first.is_ascii_alphabetic() && first != '_' && first != '$' {
        return false;
    }
    if chars.any(|c| !c.is_ascii_alphanumeric() && c != '_' && c != '$') {
        return false;
    }
    !is_reserved_word(name)
}

fn is_reserved_word(name: &str) -> bool {
    matches!(
        name,
        "await"
            | "break"
            | "case"
            | "catch"
            | "class"
            | "const"
            | "continue"
            | "debugger"
            | "default"
            | "delete"
            | "do"
            | "else"
            | "enum"
            | "export"
            | "extends"
            | "false"
            | "finally"
            | "for"
            | "function"
            | "if"
            | "import"
            | "in"
            | "instanceof"
            | "new"
            | "null"
            | "return"
            | "super"
            | "switch"
            | "this"
            | "throw"
            | "true"
            | "try"
            | "typeof"
            | "var"
            | "void"
            | "while"
            | "with"
            | "yield"
            | "implements"
            | "interface"
            | "let"
            | "package"
            | "private"
            | "protected"
            | "public"
            | "static"
    )
}

/// Reserved words cannot be BindingIdentifiers (`function delete()`).
fn push_declared_fn(out: &mut String, name: &str, signature: &str) {
    if is_binding_identifier(name) {
        out.push_str("export declare function ");
        out.push_str(name);
        out.push_str(signature);
        out.push('\n');
        return;
    }
    let alias = format!("{name}Path");
    out.push_str("declare function ");
    out.push_str(&alias);
    out.push_str(signature);
    out.push_str(" export { ");
    out.push_str(&alias);
    out.push_str(" as ");
    out.push_str(name);
    out.push_str(" };\n");
}

pub fn host_stub_path(root: &Path, specifier: &str) -> Option<PathBuf> {
    let folder = package_folder(specifier)?;
    Some(
        root.join("frameworks")
            .join(folder)
            .join("src")
            .join("host.gen.ts"),
    )
}

pub fn write_host_stubs(root: &Path) -> Result<(), String> {
    for module in first_party_modules() {
        let Some(path) = host_stub_path(root, module.specifier) else {
            continue;
        };
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|error| format!("{path:?}: {error}"))?;
        }
        std::fs::write(&path, host_stub_source(&module))
            .map_err(|error| format!("{}: {error}", path.display()))?;
    }
    Ok(())
}

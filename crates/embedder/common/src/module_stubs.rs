//! TypeScript declarations for the native `@impasto/<pkg>` modules.

use std::path::{Path, PathBuf};
use std::sync::Arc;

use session::Module;

use crate::diagnostics::{self, DevtoolsContext, DiagnosticsHub};
use crate::modules::{
    app_state, async_storage, clipboard, file_system, linking,
    memory::{DeniedPermissions, MemoryClipboard, MemoryStorage, NullLinking},
    permissions,
};

pub fn first_party_modules() -> Vec<Module> {
    let clipboard_host = MemoryClipboard::new("");
    let storage = MemoryStorage::new("/tmp/file-system");
    vec![
        app_state(session::shared("active".to_owned())),
        linking(Arc::new(NullLinking), session::shared(None)),
        clipboard(clipboard_host),
        file_system(Arc::clone(&storage) as _),
        async_storage(storage),
        permissions(Arc::new(DeniedPermissions)),
        diagnostics::module(
            Arc::new(DiagnosticsHub::new()),
            DevtoolsContext {
                enabled: true,
                source_map: None,
                app_state: session::shared("active".to_owned()),
                os: "test",
                os_version: String::new(),
                dump: None,
            },
        ),
    ]
}

pub fn package_folder(specifier: &str) -> Option<&str> {
    let name = specifier.strip_prefix("@impasto/")?;
    let valid = !name.is_empty()
        && name
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'-');
    valid.then_some(name)
}

pub fn module_stub_source(module: &Module) -> Result<String, String> {
    let declaration = module
        .typescript_declaration()
        .map_err(|error| error.to_string())?;
    Ok(format!(
        "// Generated by `cargo run -p embedder --bin module-stubs`. Do not edit.\n{declaration}"
    ))
}

pub fn module_stub_path(root: &Path, specifier: &str) -> Option<PathBuf> {
    let folder = package_folder(specifier)?;
    Some(
        root.join("packages")
            .join(folder)
            .join("src")
            .join("native.d.ts"),
    )
}

pub fn write_module_stubs(root: &Path) -> Result<(), String> {
    for module in first_party_modules() {
        let Some(path) = module_stub_path(root, module.specifier) else {
            continue;
        };
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|error| format!("{path:?}: {error}"))?;
        }
        std::fs::write(&path, module_stub_source(&module)?)
            .map_err(|error| format!("{}: {error}", path.display()))?;
    }
    Ok(())
}

pub fn check_module_stubs(root: &Path) -> Result<(), String> {
    for module in first_party_modules() {
        let Some(path) = module_stub_path(root, module.specifier) else {
            continue;
        };
        let current = std::fs::read_to_string(&path)
            .map_err(|error| format!("{}: {error}", path.display()))?;
        if current != module_stub_source(&module)? {
            return Err(format!(
                "{} is stale; run `cargo run -p embedder --bin module-stubs`",
                path.display()
            ));
        }
    }
    Ok(())
}

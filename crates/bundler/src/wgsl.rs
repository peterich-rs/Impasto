//! Generated shader modules and their named uniform layout.

use std::{
    collections::BTreeMap,
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
};

use anyhow::{Context, Result};
use engine::scene::shader::{MAX_SHADER_SOURCE_BYTES, MAX_SHADER_UNIFORM_BYTES};
use serde_json::json;
use shader::UniformField;

fn fields(source: &str) -> Result<Vec<UniformField>> {
    shader::uniform_fields(source, MAX_SHADER_SOURCE_BYTES, MAX_SHADER_UNIFORM_BYTES)
        .map_err(anyhow::Error::msg)
}

pub(crate) fn module(source: &str) -> Result<String> {
    shader::validate_portability(source, MAX_SHADER_SOURCE_BYTES).map_err(anyhow::Error::msg)?;
    let fields = fields(source)?;
    let entries = fields
        .iter()
        .map(|field| json!([field.name, field.index, field.components]))
        .collect::<Vec<_>>();
    let float_count = fields
        .iter()
        .map(|field| field.index + field.components)
        .max()
        .unwrap_or_default();
    Ok(format!(
        r#"
export default {source};
const fields = {entries};
export const uniformIndex = Object.freeze(Object.fromEntries(fields.map(([name, index]) => [name, index])));
export function packUniforms(values) {{
  const bytes = new Uint8Array({float_count} * 4);
  const view = new DataView(bytes.buffer);
  for (const [name, index, count] of fields) {{
    const value = values[name];
    if (count === 1) {{
      if (!Number.isFinite(value)) throw new TypeError(`Expected f32 uniform ${{name}}`);
      view.setFloat32(index * 4, value, true);
      continue;
    }}
    if (!value || value.length !== count) throw new TypeError(`Expected ${{count}} values for ${{name}}`);
    for (let i = 0; i < count; i++) {{
      if (!Number.isFinite(value[i])) throw new TypeError(`Expected f32 uniform ${{name}}[${{i}}]`);
      view.setFloat32((index + i) * 4, value[i], true);
    }}
  }}
  return bytes;
}}
"#,
        source = serde_json::to_string(source)?,
        entries = serde_json::to_string(&entries)?
    ))
}

/// TypeScript declarations for each resolved WGSL asset.
#[derive(Debug)]
pub struct ShaderDeclarations {
    /// Global layout map and ambient declarations for unique import suffixes.
    pub ambient: String,
    /// Declaration modules relative to the app's generated shader type root.
    pub modules: BTreeMap<PathBuf, String>,
}

/// Generates the ambient TypeScript declarations for an app's WGSL shaders.
///
/// # Errors
/// Reports filesystem failures and invalid effect uniform layouts.
pub fn shader_declarations(root: &Path) -> Result<String> {
    shader_types(root).map(|types| types.ambient)
}

/// Generates ambient declarations and path-specific modules for the app's WGSL shaders.
///
/// # Errors
/// Reports filesystem failures and invalid effect uniform layouts.
pub fn shader_types(root: &Path) -> Result<ShaderDeclarations> {
    let mut layouts = BTreeMap::new();
    collect(root, &root.join("src"), &mut layouts)?;
    collect(root, &root.join("assets"), &mut layouts)?;

    let mut names = BTreeMap::new();
    for path in layouts.keys() {
        *names.entry(path.file_name()).or_insert(0usize) += 1;
    }

    let mut ambient = String::from("// Generated by Impasto.\ninterface ImpastoShaderUniforms {\n");
    let mut declarations = String::new();
    let mut modules = BTreeMap::new();
    for (path, layout) in &layouts {
        let name = path.to_string_lossy().replace('\\', "/");
        writeln!(ambient, "  {name:?}: {{")?;
        for field in layout {
            let ty = if field.components == 1 {
                "number".to_owned()
            } else {
                format!(
                    "readonly [{}]",
                    vec!["number"; field.components as usize].join(", ")
                )
            };
            writeln!(ambient, "    {:?}: {ty};", field.name)?;
        }
        writeln!(ambient, "  }};")?;

        let mut module = String::from("// Generated by Impasto.\n");
        exports(&mut module, &name, layout, "")?;
        modules.insert(path.with_extension("d.wgsl.ts"), module);
        if names.get(&path.file_name()) == Some(&1)
            && let Some(filename) = path.file_name().and_then(|filename| filename.to_str())
        {
            writeln!(
                declarations,
                "declare module {:?} {{",
                format!("*/{filename}")
            )?;
            exports(&mut declarations, &name, layout, "  ")?;
            writeln!(declarations, "}}")?;
        }
    }
    ambient.push_str("}\n");
    ambient.push_str(&declarations);
    Ok(ShaderDeclarations { ambient, modules })
}

fn exports(
    text: &mut String,
    name: &str,
    layout: &[UniformField],
    indent: &str,
) -> std::fmt::Result {
    writeln!(text, "{indent}const source: string;")?;
    writeln!(text, "{indent}export default source;")?;
    writeln!(text, "{indent}export const uniformIndex: {{")?;
    for field in layout {
        writeln!(
            text,
            "{indent}  readonly {:?}: {};",
            field.name, field.index
        )?;
    }
    writeln!(text, "{indent}}};")?;
    writeln!(
        text,
        "{indent}export function packUniforms(values: ImpastoShaderUniforms[{name:?}]): Uint8Array;"
    )
}

fn collect(
    root: &Path,
    path: &Path,
    layouts: &mut BTreeMap<PathBuf, Vec<UniformField>>,
) -> Result<()> {
    let entries = match fs::read_dir(path) {
        Ok(entries) => entries,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(error.into()),
    };
    for entry in entries {
        let entry = entry?;
        let path = entry.path();
        if entry.file_type()?.is_dir() {
            collect(root, &path, layouts)?;
        } else if path
            .extension()
            .is_some_and(|extension| extension == "wgsl")
        {
            let layout = fields(&fs::read_to_string(&path)?)
                .with_context(|| format!("{}", path.display()))?;
            layouts.insert(path.strip_prefix(root)?.to_path_buf(), layout);
        }
    }
    Ok(())
}

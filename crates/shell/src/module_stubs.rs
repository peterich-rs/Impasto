//! TypeScript declarations for the native `@impasto/<pkg>` modules.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::sync::Arc;

use session::{Invoke, Module};

use crate::diagnostics::{self, DevtoolsContext, DiagnosticsHub};
use crate::modules::{
    app_state, async_storage, clipboard, file_system, linking,
    memory::{DeniedPermissions, MemoryClipboard, MemoryStorage, NullLinking},
    permissions,
};

pub fn first_party_modules() -> Vec<Module> {
    let clipboard_host = MemoryClipboard::new("");
    let storage = MemoryStorage::new("/tmp/file-system");
    vec![
        app_state(session::shared("active".to_owned())),
        linking(Arc::new(NullLinking), session::shared(None)),
        clipboard(clipboard_host),
        file_system(Arc::clone(&storage) as _),
        async_storage(storage),
        permissions(Arc::new(DeniedPermissions)),
        diagnostics::module(
            Arc::new(DiagnosticsHub::new()),
            DevtoolsContext {
                enabled: true,
                source_map: None,
                app_state: session::shared("active".to_owned()),
                os: "test",
                os_version: String::new(),
                dump: None,
            },
        ),
    ]
}

pub fn package_folder(specifier: &str) -> Option<&str> {
    let name = specifier.strip_prefix("@impasto/")?;
    (!name.is_empty() && !name.contains('/')).then_some(name)
}

pub fn module_stub_source(module: &Module) -> Result<String, String> {
    let mut out =
        String::from("// Generated by `cargo run -p shell --bin module-stubs`. Do not edit.\n");
    if !module.exports.typescript.is_empty() {
        out.push('\n');
        out.push_str(module.exports.typescript);
        out.push_str("\n\n");
    }
    let object = module.exports.object;
    let name = module.name;
    if object {
        let _ = writeln!(out, "\nexport interface {name} {{");
    }
    for method in &module.methods {
        let types = method.types.ok_or_else(|| {
            format!(
                "{}.{} has no TypeScript signature",
                module.specifier, method.name
            )
        })?;
        let parameters = types.parameters;
        let returns = types.returns;
        let signature = match method.invoke {
            Invoke::Sync(_) => format!("({parameters}): {returns};"),
            Invoke::Promise(_) => format!("({parameters}): Promise<{returns}>;"),
        };
        push_method(&mut out, method.name, &signature, object);
    }
    let listener_methods = ["addEventListener", "removeEventListener"];
    for listener in listener_methods {
        for event in module.exports.events {
            let signature = format!(
                "(type: {:?}, listener: (event: {}) => void): void;",
                event.name, event.payload
            );
            push_method(&mut out, listener, &signature, object);
        }
    }
    if object {
        let _ = writeln!(out, "}}\n\nexport declare const {name}: {name};");
    }
    Ok(out)
}

fn is_binding_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    if !first.is_ascii_alphabetic() && first != '_' && first != '$' {
        return false;
    }
    if chars.any(|c| !c.is_ascii_alphanumeric() && c != '_' && c != '$') {
        return false;
    }
    !is_reserved_word(name)
}

fn is_reserved_word(name: &str) -> bool {
    matches!(
        name,
        "await"
            | "break"
            | "case"
            | "catch"
            | "class"
            | "const"
            | "continue"
            | "debugger"
            | "default"
            | "delete"
            | "do"
            | "else"
            | "enum"
            | "export"
            | "extends"
            | "false"
            | "finally"
            | "for"
            | "function"
            | "if"
            | "import"
            | "in"
            | "instanceof"
            | "new"
            | "null"
            | "return"
            | "super"
            | "switch"
            | "this"
            | "throw"
            | "true"
            | "try"
            | "typeof"
            | "var"
            | "void"
            | "while"
            | "with"
            | "yield"
            | "implements"
            | "interface"
            | "let"
            | "package"
            | "private"
            | "protected"
            | "public"
            | "static"
    )
}

fn push_method(out: &mut String, name: &str, signature: &str, object: bool) {
    if object {
        let _ = writeln!(out, "  {name}{signature}");
    } else if is_binding_identifier(name) {
        let _ = writeln!(out, "export declare function {name}{signature}");
    } else {
        // `delete` is a valid export name, but not a function binding.
        let _ = writeln!(
            out,
            "declare function ${name}{signature}\nexport {{ ${name} as {name} }};"
        );
    }
}

pub fn module_stub_path(root: &Path, specifier: &str) -> Option<PathBuf> {
    let folder = package_folder(specifier)?;
    Some(
        root.join("packages")
            .join(folder)
            .join("src")
            .join("native.d.ts"),
    )
}

pub fn write_module_stubs(root: &Path) -> Result<(), String> {
    for module in first_party_modules() {
        let Some(path) = module_stub_path(root, module.specifier) else {
            continue;
        };
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|error| format!("{path:?}: {error}"))?;
        }
        std::fs::write(&path, module_stub_source(&module)?)
            .map_err(|error| format!("{}: {error}", path.display()))?;
    }
    Ok(())
}
